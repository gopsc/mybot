"""Create a minimal three-layer robot skeleton without touching hardware."""
from __future__ import annotations

import re
from pathlib import Path

from .errors import ScriptError

_NAME = re.compile(r"[A-Za-z][A-Za-z0-9_-]*\Z")

_DRIVER = '''"""Generated by ``pymybot new``. Replace the sample ping with real I/O."""


class Driver:
    def __init__(self, context):
        self.context = context

    def build(self, data):
        self.context.check()
        return {"result": "OK"}

    def call(self, data):
        self.context.check()
        return {"result": "OK", "ping": data.get("ping", 1)}

    def safe(self, data):
        # Optional best-effort stop hook, called before destroy on abort.
        self.context.check()
        return {"result": "OK"}

    def destroy(self, data):
        return {"result": "OK"}
'''

_SQL = '''/* {title}: generated by `pymybot new`.
 *
 * Add bus/address columns here, then declare the same columns in Driver.build/
 * call or the driver's metadata dictionary.
 */
CREATE TABLE {table} (name String);
INSERT INTO {table} (name) VALUES ('{variable}');
'''

_ACTION = '''# {title}: generated by `pymybot new`.
# Run with:
#   pymybot run --robot robots/{slug}.sql --input scripts/{slug}.mt
@Action
{variable}.ping;
1;
@
'''


def _class_name(name):
    if not _NAME.fullmatch(name):
        raise ScriptError("Robot name must start with a letter and contain only letters, digits, '_' or '-'")
    parts = [part for part in re.split(r"[-_]+", name) if part]
    if not parts:
        raise ScriptError("Robot name must contain a letter")
    return "".join(part[:1].upper() + part[1:] for part in parts)


def create_robot(root, name, *, force=False):
    """Write a runnable SQL/driver/MT skeleton under ``root``.

    All target paths are checked before writing, so a refusal does not leave a
    half-created robot behind.
    """
    root = Path(root).absolute()
    table = _class_name(name)
    slug = name.lower()
    variable = table[:1].lower() + table[1:] + "0"
    targets = {
        root / "robots" / f"{slug}.sql": _SQL.format(title=table, table=table, variable=variable),
        root / "scripts" / f"{slug}.mt": _ACTION.format(title=table, variable=variable, slug=slug),
        root / "modules" / f"{table}.py": _DRIVER,
    }
    existing = sorted(str(path) for path in targets if path.exists())
    if existing and not force:
        raise ScriptError("Refusing to overwrite existing files (use --force): " + ", ".join(existing))
    created = []
    for path, content in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(str(path))

    commands = [
        f"pymybot check --module-path modules --robot robots/{slug}.sql --input scripts/{slug}.mt",
        f"pymybot run --module-path modules --robot robots/{slug}.sql --input scripts/{slug}.mt --timeout 10",
    ]
    return {"root": str(root), "robot": f"robots/{slug}.sql", "script": f"scripts/{slug}.mt",
            "driver": f"modules/{table}.py", "created": created, "commands": commands}
